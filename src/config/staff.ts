export type ExpertiseArea = (typeof EXPERTISE_AREAS)[number];

/**
 * How student technical fields (student survey Q6) relate to staff expertise areas.
 * Used by the transparent matching logic in lib/matching.ts.
 */
export const FIELD_TO_EXPERTISE: Record<TechnicalField, ExpertiseArea[]> = {
  AI_ML: ["ARTIFICIAL_INTELLIGENCE", "DATA_ANALYTICS"],
  CYBERSECURITY: ["CYBERSECURITY", "NETWORKING"],
  SOFTWARE: ["PROGRAMMING"],
  ROBOTICS: ["ROBOTICS", "AUTOMATION", "EMBEDDED_SYSTEMS"],
  EMBEDDED_IOT: ["EMBEDDED_SYSTEMS", "ELECTRONICS"],
  NETWORKING: ["NETWORKING", "COMMUNICATIONS"],
  ELECTRONICS: ["ELECTRONICS"],
  DATA_SCIENCE: ["DATA_ANALYTICS", "ARTIFICIAL_INTELLIGENCE"],
  SPACE: ["SPACE_SYSTEMS", "COMMUNICATIONS"],
  DESIGN_3D: ["ENGINEERING_DESIGN"],
  OTHER: [],
};

/** Technical fields a staff expertise area can help prepare students for (inverse of the map above). */
export function fieldsForExpertise(area: ExpertiseArea): TechnicalField[] {
  return TECHNICAL_FIELDS.filter((f) => FIELD_TO_EXPERTISE[f].includes(area));
}

